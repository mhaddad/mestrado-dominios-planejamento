/* a new forward chaining planner by focusing on a goal, and try solve the
   goal before moving to anything else */
/* March 2000 */
/* 1. loop control by loop(_,_): will get much better plans but slower;
   2. if loop control is on, then turn on backtracking on choose_a_goal
      in find_plan1(G,P,Stack,P1); otherwise, turn it off. If there the
      loop control is off, then turn off backtracking will not lose any
      solution when the following is true: a compound goal is achievable
      iff each simple goal in it is achievable.
   3. goal ordering by order_goal(L1,L2,P): order compound goals (lists of
      simple goals) in L1 according to the number of simple goals in them
      that are already true in do(P,S0): work faster on many, but slower on
      some.
*/

/* K=0: no loop detecting, full backtracking, and deterministic
   K=1: no loop detecting, no backtracking, and deterministic
   K=2: loop detecting, full backtracking, and deterministic
   K=3: no loop detecting, no backtracking, and randomized
*/

/* K=0 and K=2 are so sloww, they are not really worth it */
/* for K=1 and K=3, the planner is complete if for any goal G, if
   it is achievable in S, then for any g in G, and any plan P for g, G is
   still achievable in do(P,S).
*/

/* deterministic versions may run into infinite cycle, see
   cycle.pl for an example. Solved by the new version now 20-4-2000 */

/* in this planner, a plan is a list in reverse order: the first action
   is the last element: to change it into the regular order, changes clauses
   marked by "reverse"  */

find_plan1(G,P,K) :-
	find_plan1(G,P1,[],[],1,K), %K is the maximum length of P1 or K=0
	post_process(P1,P2),
	reverse(P2,P).

/* post_process: get rid off pairs of complementary actions */

post_process(P,P1) :- 
	post_process1(P,P2), 
	((P=P2, P1=P);
	 post_process(P2,P1)),
	!.

post_process1([],[]).
post_process1([A],[A]).
post_process1([A2,A1|P],P1) :-   complement_action(A1,A2), 
	!, post_process1(P,P1).
post_process1([A1,A2|P],[A1|P1]) :-  
	post_process1([A2|P],P1).

/* find_plan1(G,P,Stack,P0,K,Max): find a plan P of G starting in do(P0,S0),
   where Stack is the current stack of goals, K is the control number, and Max
   is the maximum length of plan allowed */

find_plan1(G,P,_,P,K,Max) :-    
	holds_plan(G,P), 
	!.
find_plan1(G,P,Stack,P1,K,Max) :- %Max is the maximum length of P allowed
	(G=[SimpleG];
	 choose_a_goal(G,P1,SimpleG,K)),
	 (K=0;
	  K=2; 
	  ((K=1;K=3), !)), % allow backtracking when loop control is on
	find_plan_sg1(SimpleG,G,P2,[SimpleG|Stack],P1,K,Max),
	(Max=0; (length(P2,LP), LP =< Max)),
	(((K=0; K=1; K=2),
	  delete(G,SimpleG,G1),   /* for deterministic version:
                             when a simple goal is achieved, move
                             it to the end of the queue in case
			     it is made false again and needs to
			     be re-achieved */
	  append(G1,[SimpleG],G2),
	  find_plan1(G2,P,Stack,P2,K,Max));
	 (K=3,
	  find_plan1(G,P,Stack,P2,K,Max))).

							     
/* Stack is the stack of the simple goals the planner is working on */

find_plan_sg1(SimpleG,Gs,P,Stack,P1,K,Max) :-  
	solve_a_goal(SimpleG,Gs,P1,Stack,Action,Goal,K),
	((Action = nil, Goal =[],     %already true
	  P=P1);
	 (Action \== nil, Goal = [],  %made true by Action
          (K=0;  % loop detecting control
	   K=1;
	   K=3;
	   (K=2, \+ loop(P1,Action))),
	 (state([Action|P1],_);
	     (\+ state([Action|P1],_), 
	      state(P1,S1), hypo_progress(Action,S1,S2),
	      assert(state([Action|P1],S2)),
	      retractall(state(P1,_)));
	     (\+ state([Action|P1],_), 
	      \+ state(P1,_), initial_state(S),
	      strips_hypo_progress_plan([Action|P1],S,S2),
	      assert(state([Action|P1],S2)))),
	  find_plan_sg1(SimpleG,Gs,P,Stack,[Action|P1],K,Max)); /*reverse order */
	 (Goal\==[],          /* recurse to a subgoal */
          find_plan1(Goal,P3,Stack,P1,K,Max),
	  find_plan_sg1(SimpleG,Gs,P,Stack,P3,K,Max))).
%	!.   %another backtrack control point: no matter what, don't look
             %for another way to achieving a simple goal. Actually, allowing
             %backtrack here would lead to vicious cycles

/* the length of G is always > 1, and none of the goals in G are true */

choose_a_goal(G,P,NewSG,K) :-   
	(K=0;K=1;K=2),  %deterministic version
	((precedence(_,_,_),  % are there are control information?
	  first_simple_goal(G,P,NewSG));
	 (\+ precedence(_,_,_),
	   member(NewSG,G))).         

/* a randomized version. */

choose_a_goal(G,P,NewSG,K) :-   
	K=3,  %randomized version
	random_member_many(NewSG,G).

first_simple_goal(G,P,NewSG) :-
	member(NewSG1,G),
	\+ holds_plan([NewSG1],P),  
	first_simple_goal(G,NewSG1,NewSG1,NewSG,[NewSG1],P).

/* SG1 is the current goal, SG2 is the current first goal that is not
   true in do(P,S), and SG is the one to be computed */

first_simple_goal(G,SG1,SG2,SG,Stack,P) :-
	member(X,G),
	\+ member(X,Stack),
	precedence(X,SG1,P),
	((\+ holds_plan([X],P),
	  !,
	  first_simple_goal(G,X,X,SG,[X|Stack],P));
	 first_simple_goal(G,X,SG2,SG,[X|Stack],P)).
first_simple_goal(G,SG1,SG2,SG2,Stack,P).


/* try at most N times to get a random member X of Xs that has property G
If fail after N tries, then get the first X in Xs that has property G.
The whole thing fail when no X in Xs has property G */

random_member(X,Xs,G,N) :- random_member(X,Xs,G,N,1).
random_member(X,Xs,G,N,K) :- 
	K < N,
	((random_member(X,Xs),
	  G);
	 (M is K+1,
          random_member(X,Xs,G,N,M))),
	!.
random_member(X,Xs,G,N,N) :- 
	member(X,Xs),
	G.

/* random members of a list: allows backtracking until all members of the list
   have been chosen */

random_member_many(X, Xs) :-
	random_member(X1,Xs),
	(X = X1;
	 (delete(Xs,X1,Xs1), Xs1 \== [],
	 random_member_many(X,Xs1))).

/* random members of a list: allows at most N backtracking */

random_member_many(X, Xs, 1) :- !, random_member(X,Xs).
random_member_many(X, Xs, N) :- 
	random_member(X1,Xs),
	(X = X1;
	 (delete(Xs,X1,Xs1), Xs1 \== [], M is N-1,
	 random_member_many(X,Xs1,M))).


solve_a_goal(G,_,P,_,nil,[],_) :- 
	holds_plan([G],P), !.
%user wants to do it
solve_a_goal(G,Gs,P,Stack,A,Goal,K) :-  
	(K=1;K=2;K=0),     %this only makes sense for deterministic version
	solve_a_goal(G,A1,Goal1,Gs,P), %user want to do it
	!,  %don't try next one when the user want to do it
	((A=A1,Goal=Goal1);
	 (solve_a_goal(G,A2,Goal2,Gs,P),
	  \+ (A2=A1, Goal2=Goal1),
	  A=A2, Goal=Goal2)).
%check first that common goals have been achieved when there is no control
%knowledge
solve_a_goal(G,Gs,P,Stack,[],Goal,K) :- 
	(K=0;K=1;K=2),
	findall(GXV, (
	 effect(A,G,[],_,_), poss(A,XV,_),
	 static_fluent_holds(XV),
	 ground_subset(XV,GXV),
	 \+ unachievable(GXV)), LL),
	LL\==[],
	intersection(LL,Goal),
	Goal\==[],
	\+ holds_plan(Goal,P),
	!,  %if the common goals are not true yet, go achieve it, period!
	\+ (member(SG1,Goal), member(SG1,Stack)).
                    /* none of the simple goals in Goal can be in the stack */

solve_a_goal(G,Gs,P,_,A,[],K) :-  %found an action that makes G true
	(K=0;K=1;K=2),
        effect(A1,G,[],Eq,_),
	poss(A1,L,Eq1),
	holds_plan(L,P),
	static_holds(Eq), static_holds(Eq1),
	!,   %don't try next one when there is an action that can do the job
	((\+ action_loop(A1,P), 
	  \+ (member(SG,Gs), effect(A1,-SG,[],Eqs,_), static_holds(Eqs)),
	  A=A1);  %prefers the one that does not make Gs false
	 (effect(A2,G,[],Eq2,_), 
	  poss(A2,L2,Eq3),
	  holds_plan(L2,P),
	  static_holds(Eq2), static_holds(Eq3), A2\==A1,
	  \+ action_loop(A2,P), 
	  \+ (member(SG1,Gs), effect(A2,-SG1,[],Eqs1,_), static_holds(Eqs1)),
	  A=A2);
	  %otherwise, try one that will make Gs false
	 (effect(A3,G,[],Eq4,_), 
	  poss(A3,L3,Eq5),
	  holds_plan(L3,P),
	  static_holds(Eq4), static_holds(Eq5), 
	  \+ action_loop(A3,P), 
	  make_goal_false(A3,Gs),
	  A=A3)).
%	!.                 %for deterministic version, one action is enough


%if no action make the goal true, then pick an action to regress to,
%with priority given to the common goal in an action
%type first
solve_a_goal(G,Gs,P,Stack,[],Goal,K) :- 
	(K=0;K=1;K=2),
	action_name(An,_,_),
	findall(GXV, (
	 effect(A,G,[],_,_),
	 A =.. [An|_],
	 poss(A,XV,_),
	 static_fluent_holds(XV),
	 ground_subset(XV,GXV),
	 \+ unachievable(GXV)), LL),
	intersection(LL,TGoal),
	\+ (member(SG1,TGoal), member(SG1,Stack)),
	\+ unachievable(TGoal),	
	temp_pred(G,An,Stack,Goal,P,TGoal).
temp_pred(G,An,Stack,Goal,P,TGoal) :-
	\+ holds_plan(TGoal,P), !,
	  Goal=TGoal.
temp_pred(G,An,Stack,Goal,P,TGoal) :-
	effect(A0,G,[],Eq1,_), poss(A0,Goal,Eq2),
	A0 =.. [An|_],
	static_fluent_holds(Goal),
	get_ground_action(A0), /* all variables must be in A0 */
        static_holds(Eq1), static_holds(Eq2),
	\+ unachievable(Goal),
	\+ (member(SG11,Goal), member(SG11,Stack)).
	 

/* get a first action A that would lead to SimpleG in do(P1,s0), given
   that Stack is current set of simple goals that the planner has been
   trying to get a first action */

first_action(SimpleG,Gs,Stack,P1,A,K) :-
	solve_a_goal(SimpleG,Gs,P1,Stack,Action,Goal,K),
	((Action = nil, Goal =[],     %already true
	  A=Action);
	 (Goal=[],Action \== nil,  %made true by Action
          (K=0;  % loop detecting control
	   K=1;
	   K=3;
	   (K=2, \+ loop(P1,Action))),
	  A=Action);
	 (Goal\==[],          /* recurse to a subgoal */
          member(NewSG,Goal),
	  \+ holds_plan([NewSG],P1),
	  first_action(NewSG,Goal,[NewSG|Stack],P1,A,K))),
	!.  

/* how good an action A is compared to the actions in AL for achieving G, 
   and AL1 is AL with duplicates removed */

heuristic(A,AL1,AL,G,N) :-
	findall(X, member(A,AL), L1),
	length(L1,N1),  %the number of A's in AL
	findall(X, (member(X,G), 
	            effect(A,-X,[],Eq,_), static_holds(Eq)), L2),
	length(L2,N2),  %the number of goals in G made false by A
	findall(X, (member(X,G), 
	            effect(A,X,[],Eq,_), static_holds(Eq)), L3),
	length(L3,N3),  %the number of goals in G made true by A
	findall(X, (member(X,AL1), X\==A, poss(X,Poss,_),
	            make_goal_false(A,Poss)), L4),
	length(L4,N4),  %the number of actions in AL1 made not executable by A
	N is (N2+N4)/(N1+(N1*N3)).

make_goal_false(A,Poss) :- member(X,Poss), effect(A,-X,[],Eq,_),
	static_holds(Eq), !.



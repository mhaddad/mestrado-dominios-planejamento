get_object_domain(File,Domains) :- get_object_domain(File,Domains,[],[]).

get_object_domain(File,Domains,Domains1,Domain) :- 
    read_a_word(File,X),
    ((X=')',
      ((Domains1=[],Domains=[[object,Domain]]);
       (Domains1\==[], Domains=Domains1)));
     (X='-',
      read_a_word(File,Type),
      get_object_domain(File,Domains,[[Type,Domain]|Domains1],[]));
     get_object_domain(File,Domains,Domains1,[X|Domain])),
    !.


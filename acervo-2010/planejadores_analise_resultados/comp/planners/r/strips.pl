get_a_problem(File) :-
	retractall(temp_dname(_)),
	retractall(temp_pname(_)), 
	retractall(temp_domain(_)), retractall(temp_init(_)),
	retractall(temp_goal(_)),
  read_a_problem(File,Problem_Name),
  Problem_Name \== -1,
  read_a_word(File,_),  read_a_word(File,':domain'),
  read_a_word(File,Domain_Name),
  assert(temp_pname(Problem_Name)),
  assert(temp_dname(Domain_Name)),
  get_a_problem1(File).

get_a_problem1(File) :-
  read_a_word(File,X),
  ((X=':situation',
    read_a_word(File,Sit_Name),
    problem(Sit_Name,_,Domain1,Init1,_),
    read_a_word(File,_),   read_a_word(File,_),
    read_a_word(File,X1),
    ((X1=':init',get_init(File,Init2),
      read_a_word(File,_),read_a_word(File,_));
     (Init2=[])),
    union(Init1,Init2,Init3),
    get_goal(File,Goal), temp_pname(Problem_Name),temp_dname(Domain_Name),
    assert(problem(Problem_Name,Domain_Name,Domain1,Init3,Goal)));
   (X=':objects',
    get_object_domain(File,Domain2), assert(temp_domain(Domain2)),
    get_a_problem1(File));
   (X = ':init',
    get_init(File,Init4), assert(temp_init(Init4)),
    get_a_problem1(File));
   (X = ':goal',
    get_goal(File,Goal1), 
    temp_pname(Problem_Name),temp_dname(Domain_Name),
    temp_init(Init4),temp_domain(Domain2),
    assert(problem(Problem_Name,Domain_Name,Domain2,Init4,Goal1)));
   get_a_problem1(File)),
	retractall(temp_dname(_)),
	retractall(temp_pname(_)), 
	retractall(temp_domain(_)), retractall(temp_init(_)),
	retractall(temp_goal(_)),
   !.

/* get all problems from a file_name */

get_all_problem(File_Name) :-
	open(File_Name,read,in_file),
	retractall(problem(_,_,_,_,_)),
	get_all_problem1(in_file),
	close(in_file).

/* get_all_problem1(File) : get all the problems in a pddl file */

get_all_problem1(File) :- get_a_problem(File), !, get_all_problem1(File).
get_all_problem1(_) :- !.

/*
get_a_problem(File,DName,PName,Domains,Init,Goal) - get a problem for
action domain DName
*/

get_a_problem(File,DName,PName,Domains,Init,Goal) :-
    get_a_problem(File),
    (problem(PName,DName,Domains,Init,Goal);
     get_a_problem(File,DName,PName,Domains,Init,Goal)).


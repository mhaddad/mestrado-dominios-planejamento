holds(G,P,S) :- 
	hypo_progress_plan(P,S,NewS),
	holds(G,NewS).

/* holds_plan(G,P) if holds(G,do(P,S0)) - used state(P,S) if it exists;
   otherwise, create state(P,S) */

holds_plan(G,P) :- state(P,S), !, holds(G,S).
holds_plan(G,P) :- initial_state(S), strips_hypo_progress_plan(P,S,S1),
	assert(state(P,S1)), !, holds(G,S1).

/* here is a version of holds1(G,P,S) for context-free actions. We assume 
   here that G is a ground goal (a list of atoms), S is a state (a set of
   atoms), and P a ground plan in reverse order, i.e. the first element
   in P is the last action 
*/

holds1(G,[],S) :- subset(G,S), !.
holds1([],_,_) :- !.
holds1([SG|G],P,S) :- holds1_sg(SG,P,S), !, 
	holds1(G,P,S).

holds1_sg(-SG,P,S) :- !, \+ holds1_sg(SG,P,S).
holds1_sg(SG,[],S) :- member(SG,S).
holds1_sg(SG,[A|P],S) :- 
	effect(A,SG,[],Eq,_),
	static_holds(Eq),
	!.
holds1_sg(SG,[A|P],S) :- 
	\+ (effect(A, -(SG), [],Eq,_), static_holds(Eq)),
	holds1_sg(SG,P,S).


/* loop control: check that the new action does not undo the one 
   immediately before */

loop([Action1|_],Action) :- 
  complement_action(Action1,Action).   %P (1st argument) is in reverse order



/* complement actions: when one adds what the other deletes, and vise versa,
   futhermore, the poss list of A1 must include the add list of A2, so that
   if A1 is followed immediately by A2, then this pair of actions can be
   removed */
/* work only on context free actions */

complement_action(A1,A2) :-  
	findall(X,
	  (effect(A1, -X, [], Eq,_), 
	   static_holds(Eq)), Neg1),
	findall(X,
	  (effect(A1, X, [], Eq,_), 
	   \+ X = -(_),
	   static_holds(Eq)), Pos1),
	findall(X,
	  (effect(A2, -X, [], Eq,_), 
	   static_holds(Eq)), Neg2),
	findall(X,
	  (effect(A2, X, [], Eq,_), 
	   \+ X = -(_),
	   static_holds(Eq)), Pos2),
	sort(Neg1,Neg),
	sort(Pos2,Neg),
	sort(Pos1,Pos),
	sort(Neg2,Pos),
	poss(A1,L,_),
	subset(Pos2,L).


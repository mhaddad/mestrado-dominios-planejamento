affected(F) :- 
	effect(_, E, _, _, _),
	((E = -(E1), E1 =.. [F|_]);
	  E =.. [F|_]),
	!.

unaffacted(P) :- ((P = -P1, P1 =.. [F|_]); P =.. [F|_]), static_fluent(F).

static_fluent_holds([]).

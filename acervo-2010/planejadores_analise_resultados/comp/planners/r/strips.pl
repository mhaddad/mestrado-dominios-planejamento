/* A goal regression planner for STRIPS domain. Is has two versions:
solvep1() choose a subgoal, and commit to solving it before it moves
on to other subgoals (this is the version used in AIPS-2000 planning
competition); solvep2() computes the first actions of all the
subgoals and choose one to execute among them (this is the version that
was attempted first in planner.pl).

This planner does not rely on precomputed rules in the forms of do() and
do1() generated by solve1(N), so fluent_name(), domain(), fluent_name1()
are not needed in domain specification.
*/


get_init(File,Init) :- 
    read_a_word(File,X),
    ((X='(',
      get_an_atom_list(File,List),
      Atom =.. List,
      get_init(File,Init1),
      Init=[Atom|Init1]);
     (X=')', Init=[])),
    !.

/* craves grds gts-2) => [craves, grds, gts-2] */

get_an_atom_list(File,List) :-
    read_a_word(File,X),
    ((X=')',
      List=[]);
     (get_an_atom_list(File,List1),
      List=[X|List1])),
    !.

/*
 (and (not (craves grief-7 beef))
               (craves depression-1 beef))  => 
                 [- craves(grief-7,beef), craves(depression-1,beef)]
or
 (craves g s) => [craves(g,s)]
or
 (not (craves g s)) => [- craves(g,s)]
*/

get_goal(File,Goal) :-
    read_a_word(File,_),
    read_a_word(File,C),
    ((C = 'and',
      read_a_word(File,_),
      get_goal1(File,Goal));
     (C = 'not',
      read_a_word(File,_),
      get_an_atom_list(File,List),
      Atom =.. List,
      Goal = [-(Atom)],
      read_a_word(File,_));
     (get_an_atom_list(File,List),
      Atom =.. [C | List],
      Goal = [Atom])),
    !.

/* 
not (craves grief-7 beef))
               (craves depression-1 beef))  => 
                 [- craves(grief-7,beef), craves(depression-1,beef)]
craves grief-7 beef))
               (not (craves depression-1 beef)))  => 
                 [craves(grief-7,beef),- craves(depression-1,beef)]
*/

get_goal1(File,Goal) :-
    read_a_word(File,C),
    ((C = 'not',
     read_a_word(File,_),
     get_an_atom_list(File,List),
     Atom1 =.. List,
     Atom = -(Atom1),
     read_a_word(File,_));
    (get_an_atom_list(File,List),
     Atom =.. [C | List])),
    read_a_word(File,X),
    ((X='(',
      get_goal1(File,Goal1),
      Goal=[Atom|Goal1]);
     (X=')',
      Goal=[Atom])),
    !.

